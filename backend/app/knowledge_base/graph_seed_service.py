"""Deterministic graph seeding service.

Shared building block for programmatic graph construction. LLM extraction is
lossy on structured data (large tables, catalogs generated by pipelines), so
projects seed entities/relations directly from their own single-source
pipeline data and persist them as one confirmed extraction run anchored to a
chunk of an ingested document. Callers keep provenance (document/chunk),
review status lands as ``confirmed`` so retrieval treats it as trusted.

Contract: ``document_id`` must reference a document of ``kb_id`` whose chunks
are already indexed (upload first, then seed). The anchor chunk only carries
the extraction run's provenance; entity content comes from the caller.
"""
from __future__ import annotations

from dataclasses import dataclass

import structlog
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.knowledge_base.extraction_run_repository import (
    ExtractionRunContext,
    ExtractionRunRepository,
)
from app.knowledge_base.graph_models import KnowledgeChunk
from app.knowledge_base.graph_repository import KnowledgeGraphRepository
from app.knowledge_base.graph_schemas import (
    ChunkGraphExtraction,
    ExtractedEntity,
    ExtractedRelation,
)
from app.knowledge_base.models import Document as DocumentModel
from app.knowledge_base.models import KnowledgeBase

logger = structlog.get_logger()

MODEL_NAME_DETERMINISTIC = "deterministic"


@dataclass(frozen=True)
class GraphSeedResult:
    run_id: str
    entity_ids: list[str]
    relation_ids: list[str]
    entity_count: int
    relation_count: int


class GraphSeedError(RuntimeError):
    pass


async def seed_graph_extraction(
    session: AsyncSession,
    kb_id: str,
    document_id: str,
    entities: list[ExtractedEntity],
    relations: list[ExtractedRelation],
    *,
    prompt_version: str,
    extractor_name: str,
    anchor_chunk_marker: str | None = None,
    model_name: str = MODEL_NAME_DETERMINISTIC,
    model_params: dict | None = None,
) -> GraphSeedResult:
    """Persist caller-built entities/relations as one confirmed extraction run.

    ``anchor_chunk_marker`` selects the chunk whose content contains the given
    marker as the provenance anchor; falls back to the first chunk of the
    document when absent.
    """
    if not entities and not relations:
        raise GraphSeedError("种子内容为空：至少需要一个实体或关系")

    kb = await session.get(KnowledgeBase, kb_id)
    if kb is None:
        raise GraphSeedError(f"知识库不存在: {kb_id}")
    scene_profile_version = int(kb.scene_profile_version or 0)
    schema_version = int(kb.schema_version or 0)

    chunks = (
        (
            await session.execute(
                select(KnowledgeChunk)
                .where(
                    KnowledgeChunk.kb_id == kb_id,
                    KnowledgeChunk.document_id == document_id,
                )
                .order_by(KnowledgeChunk.chunk_index)
            )
        )
        .scalars()
        .all()
    )
    if not chunks:
        raise GraphSeedError(f"文档没有可用分块: {document_id}")

    anchor = chunks[0]
    if anchor_chunk_marker:
        anchor = next(
            (chunk for chunk in chunks if anchor_chunk_marker in (chunk.content or "")),
            anchor,
        )

    repo = KnowledgeGraphRepository(session)
    run_repo = ExtractionRunRepository(session)
    run_id = await run_repo.start(
        ExtractionRunContext(
            kb_id=kb_id,
            document_id=document_id,
            chunk_id=anchor.id,
            content_generation=int(anchor.content_generation or 0),
            scene_profile_version=scene_profile_version,
            schema_version=schema_version,
            prompt_version=prompt_version,
            model_name=model_name,
            model_params=dict(model_params or {}),
        )
    )
    extraction = ChunkGraphExtraction(
        chunk_id=anchor.id,
        extractor_name=extractor_name,
        extraction_run_id=run_id,
        entities=entities,
        relations=relations,
    )
    result = await repo.upsert_chunk_extraction(
        kb_id=kb_id,
        document_id=document_id,
        extraction=extraction,
        extraction_run_id=run_id,
    )
    await run_repo.complete(
        run_id,
        raw_response={
            "seeded_entities": len(entities),
            "seeded_relations": len(relations),
        },
        parsed_response={},
        token_usage={},
        latency_ms=0,
    )

    for record_id in result.entity_ids:
        await repo.set_review_status(
            kb_id=kb_id, kind="entity", record_id=record_id, status="confirmed"
        )
    for record_id in result.relation_ids:
        await repo.set_review_status(
            kb_id=kb_id, kind="relation", record_id=record_id, status="confirmed"
        )

    for chunk in chunks:
        chunk.graph_status = "completed"
        chunk.last_error = None
    doc = await session.get(DocumentModel, document_id)
    if doc is not None:
        doc.graph_status = "completed"
    await session.commit()

    logger.info(
        "graph_seed_completed",
        kb_id=kb_id,
        document_id=document_id,
        prompt_version=prompt_version,
        entities=len({entity.local_id for entity in entities}),
        relations=len(relations),
    )
    return GraphSeedResult(
        run_id=run_id,
        entity_ids=result.entity_ids,
        relation_ids=result.relation_ids,
        entity_count=len({entity.local_id for entity in entities}),
        relation_count=len(relations),
    )
