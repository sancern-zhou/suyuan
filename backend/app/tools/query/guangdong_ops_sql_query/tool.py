class ExecuteGuangdongMartSQLTool(LLMTool):
    """对 guangdong_mart 主数据集与 guangdong_ods 兜底层执行受控 SELECT 查询。"""

    DEFAULT_LIMIT = 50

    def __init__(self) -> None:
        self.tool_name = "execute_guangdong_mart_sql"
        self.sql_validator = SQLValidator(
            max_limit=1000,
            allowed_tables=MART_TABLES + ODS_TABLES + ["information_schema.columns"],
        )
        function_schema = {
            "name": self.tool_name,
            "description": (
                "查询广东运维工单数据集（本地PostgreSQL受控同步层，主契约"
                f"{len(MART_TABLES)}张+ODS兜底{len(ODS_TABLES)}张两套白名单）。"
                "只允许SELECT；返回数据附数据截至时间与同步状态。"
                "此工具用于工单字段级取证与统计；实时状态核对优先 execute_ops_sql_query。"
                "【用法】写SQL前先 describe_table('表名') 取字段契约（业务含义+统计口径+列结构，"
                "支持逗号分隔批量）；describe_table='tables' 返回全部表名与一句话索引。"
                "数据按水位同步非实时；查询务必带过滤条件与 LIMIT（上限1000）。"
                + _HOT_TABLE_CHEATSHEET +
                "\n【SQL方言】PostgreSQL：LIMIT 不用 TOP；日期截断 date_trunc；"
                "布尔列 IS TRUE；聚合统计优先 GROUP BY 站点/类型/区域返回小结果集。"
            ),
            "parameters": {
                "type": "object",
                "properties": {
                    "describe_table": {
                        "type": "string",
                        "description": (
                            "查看数据集字段契约（与sql二选一）：输入表名（支持逗号分隔批量、兜底表全限定名），"
                            "返回业务含义+统计口径+列结构；输入 'tables' 返回全部表名与一句话索引"
                        ),
                    },
                    "sql": {
                        "type": "string",
                        "description": "PostgreSQL SELECT查询语句（与describe_table二选一）",
                    },
                    "limit": {
                        "type": "integer",
                        "description": "返回记录数上限（默认50，最大1000）",
                        "default": 50,
                    },
                },
            },
        }
        super().__init__(
            name=self.tool_name,
            description="查询广东运维工单数据集（分析宽表/工单/明细/附件/站点/设备/中低频表单兜底，受控只读SQL）",
            category=ToolCategory.QUERY,
            function_schema=function_schema,
            version="1.2.0",
            requires_context=True,
        )

    # ------------------------------------------------------------------ 入口
    async def execute(
        self,
        context: Optional["ExecutionContext"] = None,
        describe_table: Optional[str] = None,
        sql: Optional[str] = None,
        limit: Optional[int] = None,
        **kwargs: Any,
    ) -> Dict[str, Any]:
        if describe_table and sql:
            return {"success": False, "data": None,
                    "summary": "describe_table 和 sql 参数不能同时使用"}
        if not describe_table and not sql:
            return {"success": False, "data": None,
                    "summary": "请提供 sql 或 describe_table 参数，二者必选其一"}

        if describe_table is not None:
            return await self._describe_tables(describe_table)

        if limit is None:
            limit = self.DEFAULT_LIMIT
        limit = min(limit, self.sql_validator.max_limit)
        return await self._execute_sql(sql, limit, context)

    def _mart_dsn(self) -> str:
        dsn = os.getenv("OPS_MART_DATABASE_URL", "")
        if not dsn:
            raise RuntimeError("OPS_MART_DATABASE_URL 未配置（本地同步库连接）")
        return dsn

    @staticmethod
    def _schema_of(table: str) -> Optional[str]:
        """Resolve which schema a whitelisted table lives in (None = not allowed)."""
        if table in MART_TABLE_SET:
            return MART_SCHEMA
        if table in ODS_TABLE_SET:
            return ODS_SCHEMA
        return None

    async def _connect(self):
        """search_path 同时暴露 mart 契约表与 ODS 兜底表。"""
        return await asyncpg.connect(
            self._mart_dsn(),
            server_settings={"search_path": f"{MART_SCHEMA},{ODS_SCHEMA}"},
        )

    # ------------------------------------------------------------ 表结构
    def _unknown_table_summary(self, table: str) -> str:
        """Unknown-table message with fuzzy recall: point at describe_table('tables')."""
        close = difflib.get_close_matches(
            table, MART_TABLES + ODS_TABLES, n=3, cutoff=0.6)
        hint = (
            f"相近表名：{', '.join(close)}；" if close else ""
        )
        return (
            f"表 {table} 不在白名单中。{hint}"
            f"describe_table='tables' 可列出全部 {len(MART_TABLES) + len(ODS_TABLES)} 张表名与一句话索引。"
        )

    def _table_index(self) -> List[Dict[str, Any]]:
        """All whitelisted tables with a one-line summary (on-demand, not in schema)."""
        items: List[Dict[str, Any]] = []
        for table in MART_TABLES:
            items.append({
                "table": table,
                "layer": "mart",
                "summary": _trim(MART_TABLE_GUIDES.get(table, "")),
            })
        for table in ODS_TABLES:
            items.append({
                "table": table,
                "layer": "ods_fallback",
                "summary": _trim(ODS_TABLE_GUIDES.get(table, "")),
            })
        return items

    def _guide_of(self, table: str, schema: str) -> str:
        guides = MART_TABLE_GUIDES if schema == MART_SCHEMA else ODS_TABLE_GUIDES
        return guides.get(table, "")

    async def _describe_tables(self, raw: str) -> Dict[str, Any]:
        """Per-table contract on demand: 'tables' index, or 1..N named tables."""
        request = (raw or "").strip()
        if request.lower() in TABLE_INDEX_KEYWORDS or request in TABLE_INDEX_KEYWORDS:
            items = self._table_index()
            return {
                "success": True,
                "mode": "table_index",
                "total": len(items),
                "tables": items,
                "summary": (
                    f"共 {len(items)} 张表（mart {len(MART_TABLES)} + ods 兜底 {len(ODS_TABLES)}）；"
                    "用 describe_table('表名') 取字段契约（业务含义+统计口径+列结构）。"
                ),
            }

        names = [n for n in re.split(r"[,，;；、\s]+", request) if n]
        if not names:
            return {"success": False, "data": None,
                    "summary": "describe_table 参数为空；输入表名或 'tables' 查看全部表名。"}
        if len(names) > DESCRIBE_BATCH_MAX:
            return {"success": False, "data": None,
                    "summary": f"一次最多 describe {DESCRIBE_BATCH_MAX} 张表，请分批调用。"}

        resolved: List[Tuple[str, str]] = []
        unknown: List[str] = []
        for name in names:
            table = name.strip().split(".")[-1].strip().lower()
            schema = self._schema_of(table)
            if schema is None:
                unknown.append(table)
            else:
                resolved.append((table, schema))
        if unknown:
            return {"success": False, "data": None,
                    "summary": self._unknown_table_summary(unknown[0])}

        columns_by_table = await self._fetch_columns(resolved)
        entries = []
        for table, schema in resolved:
            columns = columns_by_table.get(table, [])
            entries.append({
                "table": table,
                "schema": schema,
                "layer": "mart" if schema == MART_SCHEMA else "ods_fallback",
                "guide": self._guide_of(table, schema),
                "columns": columns,
                "summary": f"{table}: {len(columns)} 列；字段业务含义与统计口径见 guide（数据集契约）。",
            })
        rules = MART_GLOBAL_RULES + ("\n" + ODS_GLOBAL_RULES if ODS_GLOBAL_RULES else "")
        result: Dict[str, Any] = {
            "success": True,
            "mode": "table_contract",
            "tables": entries,
            "contract_rules": _trim(rules, 1600),
            "summary": "；".join(item["summary"] for item in entries),
        }
        if len(entries) == 1:
            # 单表请求保持既有顶层字段形状，老调用方不破坏。
            only = entries[0]
            result.update({
                "table": only["table"], "schema": only["schema"],
                "layer": only["layer"], "columns": only["columns"],
            })
        return result

    async def _fetch_columns(
        self, resolved: List[Tuple[str, str]]
    ) -> Dict[str, List[Dict[str, Any]]]:
        """Batch information_schema lookup for (table, schema) pairs."""
        conn = await self._connect()
        columns_by_table: Dict[str, List[Dict[str, Any]]] = {}
        try:
            for schema in (MART_SCHEMA, ODS_SCHEMA):
                tables = [t for t, s in resolved if s == schema]
                if not tables:
                    continue
                rows = await conn.fetch(
                    "SELECT table_name, column_name, data_type FROM information_schema.columns "
                    "WHERE table_schema = $1 AND lower(table_name) = ANY($2) "
                    "ORDER BY table_name, ordinal_position",
                    schema,
                    tables,
                )
                for r in rows:
                    # ODS 同步内部列（_src_incremental/_sync_batch/_synced_at）不是业务字段，
                    # 且 _synced_at 只在首插时写入，露出来会误导"数据新鲜度"判断。
                    if schema == ODS_SCHEMA and r["column_name"].startswith("_"):
                        continue
                    columns_by_table.setdefault(r["table_name"], []).append(
                        {"name": r["column_name"], "type": r["data_type"]})
        finally:
            await conn.close()
        return columns_by_table

    # ------------------------------------------------------------ 查询
    async def _execute_sql(
        self, sql: str, limit: int, context: Optional["ExecutionContext"]
    ) -> Dict[str, Any]:
        started = time.monotonic()
        status = "ok"
        row_count = 0
        try:
            sql = self.sql_validator.normalize_sql(sql)
            is_valid, error_msg = self.sql_validator.validate(sql)
            if not is_valid:
                status = "rejected"
                return {
                    "success": False,
                    "data": [],
                    "summary": (
                        f"SQL校验失败: {error_msg}。"
                        "字段口径先 describe_table('表名') 取契约（含业务含义与统计口径）；"
                        "describe_table='tables' 列出全部表名。"
                    ),
                }

            # 行数上限由外层包裹强制，不依赖 LLM 写 LIMIT；多取一行用于判定截断。
            safe_sql = f"SELECT * FROM ({sql.rstrip('; ')}) AS _mart_query LIMIT {limit + 1}"
            statement = await self._statement_timeout_sql(safe_sql)

            conn = await self._connect()
            try:
                # 契约表为裸名（search_path 先 mart 后 ods），兜底表建议写全限定名 guangdong_ods.<表名>。
                rows = await conn.fetch(statement)
                truncated = len(rows) > limit
                results = [dict(r) for r in rows[:limit]]
                row_count = len(results)
                data_as_of = await self._data_as_of(conn, sql)
            finally:
                await conn.close()

            sample_data = results
            file_path = None
            if context and len(results) > 24:
                columns = list(results[0].keys()) if results else []
                file_path = context.save_data(
                    data=results,
                    schema="sql_query_result",
                    metadata={"database": MART_SCHEMA, "sql": sql,
                              "row_count": len(results), "columns": columns},
                )
                sample_data = results[:12] + results[-12:]

            elapsed_ms = int((time.monotonic() - started) * 1000)
            return {
                "success": True,
                "data": sample_data,
                "file_path": file_path,
                "count": len(results),
                "sample_count": len(sample_data),
                "limit": limit,
                "truncated": truncated,
                "data_as_of": data_as_of,
                "summary": (
                    f"返回 {len(results)} 行（数据截至 {data_as_of}，耗时 {elapsed_ms}ms）"
                    + (f"；已达返回上限 {limit} 行，结果被截断，匹配行数更多" if truncated else "")
                ),
            }
        except Exception as exc:  # noqa: BLE001
            status = "error"
            logger.warning("guangdong_mart_sql_failed", error=str(exc))
            return {
                "success": False,
                "data": [],
                "summary": f"查询失败: {exc}。可用 describe_table 查看白名单表结构。",
            }
        finally:
            await self._audit_query(sql, row_count, status)

    async def _statement_timeout_sql(self, sql: str) -> str:
        return sql

    async def _data_as_of(self, conn: asyncpg.Connection, sql: str) -> Optional[str]:
        """以查询涉及的首个可判定表的水位给出数据截至时间。"""
        try:
            tables = self.sql_validator.extract_tables(sql)
            for table in tables:
                table = str(table).strip().strip('"').split(".")[-1].lower()
                # ODS 兜底表没有 refreshed_at，按表取同步水位（sync_table.py 维护；
                # 水位 table_name 存命令行原样，可能带大写，统一 lower 比较）。
                if table in ODS_TABLE_SET:
                    watermark = await conn.fetchval(
                        f"SELECT MAX(updated_at)::text FROM {AUDIT_SCHEMA}.ods_sync_watermark "
                        "WHERE lower(table_name) = ANY($1)",
                        [table],
                    )
                    if watermark:
                        return watermark
                    continue
                column = FRESHNESS_COLUMN.get(table)
                if not column:
                    continue
                value = await conn.fetchval(
                    f"SELECT MAX({column})::text FROM {MART_SCHEMA}.{table}"
                )
                if value:
                    return value
            # data-ops 水位（sync_table.py 维护）；旧 fetcher 水位表作为迁移期兜底。
            try:
                watermark = await conn.fetchval(
                    f"SELECT MAX(updated_at)::text FROM {AUDIT_SCHEMA}.ods_sync_watermark"
                )
            except asyncpg.UndefinedTableError:
                watermark = None
            if not watermark:
                watermark = await conn.fetchval(
                    f"SELECT MAX(updated_at)::text FROM {AUDIT_SCHEMA}.sync_watermark"
                )
            return watermark
        except Exception:  # noqa: BLE001
            return None

    async def _audit_query(self, sql: str, row_count: int, status: str) -> None:
        try:
            conn = await asyncpg.connect(self._mart_dsn())
            try:
                await conn.execute(
                    f"INSERT INTO {AUDIT_SCHEMA}.query_audit (tool, sql_text, row_count, status) "
                    "VALUES ($1, $2, $3, $4)",
                    self.tool_name,
                    (sql or "")[:8000],
                    row_count,
                    status,
                )
            finally:
                await conn.close()
        except Exception:  # noqa: BLE001
            logger.debug("guangdong_mart_query_audit_skipped")
