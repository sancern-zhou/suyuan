MART_TABLE_SET = set(MART_TABLES)
ODS_TABLE_SET = set(ODS_TABLES)


def _trim(text: str, limit: int = INDEX_SUMMARY_MAX_CHARS) -> str:
    text = (text or "").strip()
    if len(text) <= limit:
        return text
    return text[: limit - 1] + "…"


