"""广东运维工单数据集受控 SQL 查询工具（本地 PostgreSQL 同步层）。

对称 jiangsu 分支的 jiangsu_ops_sql_query：查询本地 guangdong_mart schema 的
工单数据集 + guangdong_ods 兜底层原始表，SELECT-only、表白名单、行数上限、
强制超时由外层包裹实现，每次查询审计写入 guangdong_sync.query_audit。

2026-10-24 data-ops 化：数据链路改为 data-ops 三层
（sync_table.py → guangdong_ods → dbt → guangdong_mart），不再由
guangdong_work_order fetcher 直写；contract.txt 由
projects/guangdong/data-ops/sync/gen_tool_contract.py 从 datasets/*.yaml 生成。
2026-10-25 ODS 兜底通道：同步进 guangdong_ods 的表不允许 Agent 查不到——
主契约（37 张，高频完整说明+长尾一句话）覆盖不到的表由 ods_contract.txt
（gen_ods_fallback_contract.py 生成，53 张一句话索引）托底，
引用写全限定名 guangdong_ods.<表名>，列结构用 describe_table 获取。
数据新鲜度见各表 refreshed_at（dbt 重建时间）与
guangdong_sync.ods_sync_watermark（ODS 水位）。
"""
from __future__ import annotations

import os
import re
import time
from pathlib import Path
from typing import Any, Dict, List, Optional, TYPE_CHECKING

import asyncpg
import structlog

from app.tools.base.tool_interface import LLMTool, ToolCategory
from app.utils.sql_validator import SQLValidator

if TYPE_CHECKING:
    from app.agent.context import ExecutionContext

logger = structlog.get_logger()

MART_SCHEMA = "guangdong_mart"
ODS_SCHEMA = "guangdong_ods"
AUDIT_SCHEMA = "guangdong_sync"
# dbt 各表统一附加 refreshed_at（重建时间）；data_as_of 优先取查询涉及表的新鲜度。
FRESHNESS_COLUMN = {
    "working_orders": "refreshed_at",
    "working_order_details": "refreshed_at",
    "wo_commonfile_links": "refreshed_at",
    "dim_station": "refreshed_at",
    "dim_device": "refreshed_at",
    "mart_work_order_analysis": "refreshed_at",
}


def _load_contract_file(path: Path, label: str) -> tuple:
    """Load a generated dataset contract (TABLES line + GUIDE block)."""
    text = path.read_text(encoding="utf-8")
    tables: List[str] = []
    guide_lines: List[str] = []
    in_guide = False
    for line in text.splitlines():
        if line.startswith("TABLES:"):
            tables = [t.strip() for t in line.split(":", 1)[1].split(",") if t.strip()]
        elif line.strip() == "GUIDE_START":
            in_guide = True
        elif line.strip() == "GUIDE_END":
            in_guide = False
        elif in_guide:
            guide_lines.append(line)
    if not tables or not guide_lines:
        raise RuntimeError(
            f"{label} invalid (missing TABLES or GUIDE block) — "
            "regenerate with sync/gen_*contract.py"
        )
    return tables, "\n".join(guide_lines)


def _load_contract() -> tuple:
    """Load the dataset contract generated from data-ops sync/datasets/*.yaml (single source)."""
    return _load_contract_file(
        Path(__file__).with_name("contract.txt"), "contract.txt")


def _load_ods_contract() -> tuple:
    """Load the ODS fallback whitelist generated by sync/gen_ods_fallback_contract.py.

    每张同步进 guangdong_ods 但未被主契约覆盖的表都落在这里（一句话索引），
    保证"同步的数据不允许 Agent 查不到"；缺失时降级为仅主契约并告警。
    """
    path = Path(__file__).with_name("ods_contract.txt")
    if not path.exists():
        logger.warning(
            "guangdong_ods_contract_missing",
            path=str(path),
            hint="run sync/gen_ods_fallback_contract.py to restore the ODS fallback channel",
        )
        return [], ""
    return _load_contract_file(path, "ods_contract.txt")


MART_TABLES, MART_SCHEMA_GUIDE = _load_contract()
ODS_TABLES, ODS_SCHEMA_GUIDE = _load_ods_contract()
MART_TABLE_SET = set(MART_TABLES)
ODS_TABLE_SET = set(ODS_TABLES)


class ExecuteGuangdongMartSQLTool(LLMTool):
    """对 guangdong_mart 主数据集与 guangdong_ods 兜底层执行受控 SELECT 查询。"""

    DEFAULT_LIMIT = 50

    def __init__(self) -> None:
        self.tool_name = "execute_guangdong_mart_sql"
        self.sql_validator = SQLValidator(
            max_limit=1000,
            allowed_tables=MART_TABLES + ODS_TABLES + ["information_schema.columns"],
        )
        function_schema = {
            "name": self.tool_name,
            "description": (
                "查询广东运维工单数据集（本地PostgreSQL受控同步层，主契约+ODS兜底两套白名单）。"
                "只允许SELECT；表名白名单见工具说明，兜底表引用写全限定名 guangdong_ods.<表名>；"
                "返回数据附数据截至时间与同步状态。"
                "此工具用于工单字段级取证与统计；实时状态核对优先 execute_ops_sql_query。"
                + MART_SCHEMA_GUIDE
                + ODS_SCHEMA_GUIDE
            ),
            "parameters": {
                "type": "object",
                "properties": {
                    "describe_table": {
                        "type": "string",
                        "description": "查看数据集字段结构（与sql二选一），输入白名单中的表名（兜底表同样支持）",
                    },
                    "sql": {
                        "type": "string",
                        "description": "PostgreSQL SELECT查询语句（与describe_table二选一）",
                    },
                    "limit": {
                        "type": "integer",
                        "description": "返回记录数上限（默认50，最大1000）",
                        "default": 50,
                    },
                },
            },
        }
        super().__init__(
            name=self.tool_name,
            description="查询广东运维工单数据集（分析宽表/工单/明细/附件/站点/设备/中低频表单兜底，受控只读SQL）",
            category=ToolCategory.QUERY,
            function_schema=function_schema,
            version="1.1.0",
            requires_context=True,
        )

    # ------------------------------------------------------------------ 入口
    async def execute(
        self,
        context: Optional["ExecutionContext"] = None,
        describe_table: Optional[str] = None,
        sql: Optional[str] = None,
        limit: Optional[int] = None,
        **kwargs: Any,
    ) -> Dict[str, Any]:
        if describe_table and sql:
            return {"success": False, "data": None,
                    "summary": "describe_table 和 sql 参数不能同时使用"}
        if not describe_table and not sql:
            return {"success": False, "data": None,
                    "summary": "请提供 sql 或 describe_table 参数，二者必选其一"}

        if describe_table is not None:
            table = describe_table.strip().split(".")[-1].strip().lower()
            schema = self._schema_of(table)
            if schema is None:
                return {"success": False, "data": None,
                        "summary": f"表 {describe_table} 不在白名单中。允许: {', '.join(MART_TABLES + ODS_TABLES)}"}
            return await self._describe_table(table, schema)

        if limit is None:
            limit = self.DEFAULT_LIMIT
        limit = min(limit, self.sql_validator.max_limit)
        return await self._execute_sql(sql, limit, context)

    def _mart_dsn(self) -> str:
        dsn = os.getenv("OPS_MART_DATABASE_URL", "")
        if not dsn:
            raise RuntimeError("OPS_MART_DATABASE_URL 未配置（本地同步库连接）")
        return dsn

    @staticmethod
    def _schema_of(table: str) -> Optional[str]:
        """Resolve which schema a whitelisted table lives in (None = not allowed)."""
        if table in MART_TABLE_SET:
            return MART_SCHEMA
        if table in ODS_TABLE_SET:
            return ODS_SCHEMA
        return None

    async def _connect(self):
        """search_path 同时暴露 mart 契约表与 ODS 兜底表。"""
        return await asyncpg.connect(
            self._mart_dsn(),
            server_settings={"search_path": f"{MART_SCHEMA},{ODS_SCHEMA}"},
        )

    # ------------------------------------------------------------ 表结构
    async def _describe_table(self, table: str, schema: str = MART_SCHEMA) -> Dict[str, Any]:
        conn = await self._connect()
        try:
            rows = await conn.fetch(
                "SELECT column_name, data_type FROM information_schema.columns "
                "WHERE table_schema = $1 AND table_name = $2 ORDER BY ordinal_position",
                schema,
                table,
            )
            columns = [
                {"name": r["column_name"], "type": r["data_type"]}
                for r in rows
                # ODS 同步内部列（_src_incremental/_sync_batch/_synced_at）不是业务字段，
                # 且 _synced_at 只在首插时写入，露出来会误导"数据新鲜度"判断。
                if schema != ODS_SCHEMA or not r["column_name"].startswith("_")
            ]
            layer = "mart" if schema == MART_SCHEMA else "ods_fallback"
            return {
                "success": True,
                "table": table,
                "schema": schema,
                "layer": layer,
                "columns": columns,
                "summary": f"{table}: {len(columns)} 列。字段业务含义以工具说明中的数据集约束为准。",
            }
        finally:
            await conn.close()

    # ------------------------------------------------------------ 查询
    async def _execute_sql(
        self, sql: str, limit: int, context: Optional["ExecutionContext"]
    ) -> Dict[str, Any]:
        started = time.monotonic()
        status = "ok"
        row_count = 0
        try:
            sql = self.sql_validator.normalize_sql(sql)
            is_valid, error_msg = self.sql_validator.validate(sql)
            if not is_valid:
                status = "rejected"
                return {
                    "success": False,
                    "data": [],
                    "summary": f"SQL校验失败: {error_msg}。允许的表: {', '.join(MART_TABLES + ODS_TABLES)}",
                }

            # 行数上限由外层包裹强制，不依赖 LLM 写 LIMIT；多取一行用于判定截断。
            safe_sql = f"SELECT * FROM ({sql.rstrip('; ')}) AS _mart_query LIMIT {limit + 1}"
            statement = await self._statement_timeout_sql(safe_sql)

            conn = await self._connect()
            try:
                # 契约表为裸名（search_path 先 mart 后 ods），兜底表建议写全限定名 guangdong_ods.<表名>。
                rows = await conn.fetch(statement)
                truncated = len(rows) > limit
                results = [dict(r) for r in rows[:limit]]
                row_count = len(results)
                data_as_of = await self._data_as_of(conn, sql)
            finally:
                await conn.close()

            sample_data = results
            file_path = None
            if context and len(results) > 24:
                columns = list(results[0].keys()) if results else []
                file_path = context.save_data(
                    data=results,
                    schema="sql_query_result",
                    metadata={"database": MART_SCHEMA, "sql": sql,
                              "row_count": len(results), "columns": columns},
                )
                sample_data = results[:12] + results[-12:]

            elapsed_ms = int((time.monotonic() - started) * 1000)
            return {
                "success": True,
                "data": sample_data,
                "file_path": file_path,
                "count": len(results),
                "sample_count": len(sample_data),
                "limit": limit,
                "truncated": truncated,
                "data_as_of": data_as_of,
                "summary": (
                    f"返回 {len(results)} 行（数据截至 {data_as_of}，耗时 {elapsed_ms}ms）"
                    + (f"；已达返回上限 {limit} 行，结果被截断，匹配行数更多" if truncated else "")
                ),
            }
        except Exception as exc:  # noqa: BLE001
            status = "error"
            logger.warning("guangdong_mart_sql_failed", error=str(exc))
            return {
                "success": False,
                "data": [],
                "summary": f"查询失败: {exc}。可用 describe_table 查看白名单表结构。",
            }
        finally:
            await self._audit_query(sql, row_count, status)

    async def _statement_timeout_sql(self, sql: str) -> str:
        return sql

    async def _data_as_of(self, conn: asyncpg.Connection, sql: str) -> Optional[str]:
        """以查询涉及的首个可判定表的水位给出数据截至时间。"""
        try:
            tables = self.sql_validator.extract_tables(sql)
            for table in tables:
                table = str(table).strip().strip('"').split(".")[-1].lower()
                # ODS 兜底表没有 refreshed_at，按表取同步水位（sync_table.py 维护；
                # 水位 table_name 存命令行原样，可能带大写，统一 lower 比较）。
                if table in ODS_TABLE_SET:
                    watermark = await conn.fetchval(
                        f"SELECT MAX(updated_at)::text FROM {AUDIT_SCHEMA}.ods_sync_watermark "
                        "WHERE lower(table_name) = ANY($1)",
                        [table],
                    )
                    if watermark:
                        return watermark
                    continue
                column = FRESHNESS_COLUMN.get(table)
                if not column:
                    continue
                value = await conn.fetchval(
                    f"SELECT MAX({column})::text FROM {MART_SCHEMA}.{table}"
                )
                if value:
                    return value
            # data-ops 水位（sync_table.py 维护）；旧 fetcher 水位表作为迁移期兜底。
            try:
                watermark = await conn.fetchval(
                    f"SELECT MAX(updated_at)::text FROM {AUDIT_SCHEMA}.ods_sync_watermark"
                )
            except asyncpg.UndefinedTableError:
                watermark = None
            if not watermark:
                watermark = await conn.fetchval(
                    f"SELECT MAX(updated_at)::text FROM {AUDIT_SCHEMA}.sync_watermark"
                )
            return watermark
        except Exception:  # noqa: BLE001
            return None

    async def _audit_query(self, sql: str, row_count: int, status: str) -> None:
        try:
            conn = await asyncpg.connect(self._mart_dsn())
            try:
                await conn.execute(
                    f"INSERT INTO {AUDIT_SCHEMA}.query_audit (tool, sql_text, row_count, status) "
                    "VALUES ($1, $2, $3, $4)",
                    self.tool_name,
                    (sql or "")[:8000],
                    row_count,
                    status,
                )
            finally:
                await conn.close()
        except Exception:  # noqa: BLE001
            logger.debug("guangdong_mart_query_audit_skipped")
