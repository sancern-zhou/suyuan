STATIONS = tuple(JiangxiNoiseStation(*row) for row in STATION_ROWS)
STATIONS_BY_CODE = {station.station_code.upper(): station for station in STATIONS}
STATIONS_BY_CITY = {
    city_name: tuple(station for station in STATIONS if station.city_name == city_name)
    for city_name in CITY_NAMES
}
STATIONS_BY_NAME = {_normalize_key(station.name): station for station in STATIONS}


def is_province_alias(value: Any) -> bool:
    key = _normalize_key(value)
    return key in {_normalize_key(alias) for alias in PROVINCE_ALIASES}


def canonical_city_name(value: Any) -> str | None:
    raw = str(value or "").strip()
    key = _normalize_key(raw)
    if not key:
        return None
    if key in {_normalize_key(alias) for alias in PROVINCE_ALIASES}:
        return None
    if raw in CITY_CODE_TO_NAME:
        return CITY_CODE_TO_NAME[raw]
    for name in CITY_NAMES:
        if key in {_normalize_key(name), _normalize_key(name.removesuffix("市"))}:
            return name
    return None


def resolve_city_names(values: list[str], *, default_all: bool = False) -> tuple[list[str], list[str]]:
    if not values and default_all:
        return list(CITY_NAMES), []

    resolved: list[str] = []
    warnings: list[str] = []
    for value in values:
        if is_province_alias(value):
            for city in CITY_NAMES:
                if city not in resolved:
                    resolved.append(city)
            continue
        city = canonical_city_name(value)
        if not city:
            warnings.append(f"未识别江西地市：{value}")
            continue
        if city not in resolved:
            resolved.append(city)
    return resolved, warnings


def resolve_station_records(
    *,
    cities: list[str] | None = None,
    stations: list[str] | None = None,
    station_codes: list[str] | None = None,
    default_all: bool = False,
) -> tuple[list[JiangxiNoiseStation], dict[str, Any], list[str]]:
    warnings: list[str] = []
    resolved: list[JiangxiNoiseStation] = []
    seen_codes: set[str] = set()

    def add(station: JiangxiNoiseStation) -> None:
        code = station.station_code.upper()
        if code not in seen_codes:
            seen_codes.add(code)
            resolved.append(station)

    for code in station_codes or []:
        station = STATIONS_BY_CODE.get(code.strip().upper())
        if station:
            add(station)
        else:
            warnings.append(f"未识别江西噪声站点编码：{code}")

    for value in stations or []:
        key = _normalize_key(value)
        direct = STATIONS_BY_CODE.get(str(value).strip().upper()) or STATIONS_BY_NAME.get(key)
        if direct:
            add(direct)
            continue
        matches = [
            station
            for station in STATIONS
            if key and (key in _normalize_key(station.name) or key in _normalize_key(station.address))
        ]
        if matches:
            for station in matches:
                add(station)
            if len(matches) > 1:
                warnings.append(f"站点名片段“{value}”匹配 {len(matches)} 个站点，已全部纳入查询")
        else:
            warnings.append(f"未识别江西噪声站点：{value}")

    city_values = cities or []
    if not city_values and default_all and not resolved:
        city_values = ["江西省"]
    province_requested = any(is_province_alias(value) for value in city_values)
    resolved_cities, city_warnings = resolve_city_names(city_values)
    warnings.extend(city_warnings)
    if province_requested:
        for station in STATIONS:
            add(station)
    if province_requested:
        city_iterable: tuple[str, ...] = ()
    else:
        city_iterable = tuple(resolved_cities)
    for city in city_iterable:
        for station in STATIONS_BY_CITY.get(city, ()):
            add(station)

    metadata = {
        "requested_cities": city_values,
        "resolved_cities": resolved_cities,
        "requested_stations": stations or [],
        "requested_station_codes": station_codes or [],
        "resolved_station_count": len(resolved),
        "resolved_station_codes": [station.station_code for station in resolved],
        "resolved_station_preview": [station.as_dict() for station in resolved[:20]],
        "unknown_station_not_in_city_expansion": "1872A",
    }
    return resolved, metadata, warnings
